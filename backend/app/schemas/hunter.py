from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field, field_validator


class HunterAnalyzeRequest(BaseModel):
    """
    Input contract for the AI Logic Hunter analysis endpoint.
    Accepts raw HTTP traffic and an optional comparison-group credential
    for cross-account privilege-escalation (IDOR/BOLA) assessment.
    """
    raw_traffic: str = Field(
        ...,
        min_length=10,
        description=(
            "The raw HTTP request text pasted by the operator. "
            "Must include at least the request line and one header."
        ),
        examples=[
            "POST /api/v1/user/profile HTTP/1.1\n"
            "Host: target.example.com\n"
            "Cookie: session=abc123\n"
            "Content-Type: application/json\n\n"
            '{"user_id": 1001, "role": "admin"}'
        ],
    )

    auth_context_b: Optional[str] = Field(
        default=None,
        description=(
            "Comparison-group identity credential (e.g. another test account's Cookie, "
            "JWT, or UUID) used to help the AI evaluate horizontal/vertical privilege "
            "escalation (IDOR / BOLA) feasibility. Leave empty if not applicable."
        ),
        examples=["session=xyz789; user_id=2002"],
    )

    @field_validator("raw_traffic")
    @classmethod
    def validate_raw_traffic(cls, v: str) -> str:
        """Ensure the raw traffic is not just whitespace."""
        stripped = v.strip()
        if not stripped:
            raise ValueError("raw_traffic must contain meaningful HTTP request content.")
        return stripped


class AutomationPayload(BaseModel):
    """
    A single attack-vector payload element produced by the AI reasoning engine.
    Designed for future automated fuzzing / replay execution.
    """
    phase: int = Field(
        ...,
        description="Execution phase: 1 = baseline probing, 2 = bypass & exploitation."
    )
    type: str = Field(
        ...,
        description="Vulnerability class (e.g. BOLA, IDOR, Parameter_Pollution, Race_Condition, Mass_Assignment)."
    )
    location: str = Field(
        ...,
        description="Where the target parameter resides: json_key, query_param, header, path_segment, cookie."
    )
    target_param: str = Field(
        ...,
        description="The exact parameter name to mutate (e.g. user_id, order_id, role)."
    )
    payload_string: str = Field(
        ...,
        description="The concrete payload action or replacement value to inject."
    )
    expected_match: str = Field(
        ...,
        description=(
            "The observable indicator to confirm exploitation success "
            "(e.g. HTTP 200, response length delta, specific error string)."
        ),
    )


class HunterAnalyzeResponse(BaseModel):
    """
    Output contract for the AI Logic Hunter analysis endpoint.
    Contains the structured parse result, AI-generated expert report,
    and machine-readable automation payloads.
    """
    status: str = Field(
        ...,
        description="Overall result status: 'success' or 'error'."
    )
    parsed_data: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "The structured HTTP request decomposition produced by the traffic parser. "
            "Contains: method, path, query_params, headers, body, errors."
        ),
    )
    report_markdown: str = Field(
        default="",
        description="Expert-level Markdown security analysis report generated by Gemini AI."
    )
    automation_payloads: List[AutomationPayload] = Field(
        default_factory=list,
        description="Array of structured attack-vector payloads for future automated replay."
    )
    error_message: Optional[str] = Field(
        default=None,
        description="Human-readable error description when status is 'error'."
    )


