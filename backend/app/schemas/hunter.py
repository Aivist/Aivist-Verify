class FuzzingRecordSchema(BaseModel):
    """
    Output schema for a single FuzzingRecord entry — captures the mutated
    request, raw response, differential analysis verdict, and metrics.
    """
    id: str
    finding_id: int
    payload_index: int
    sent_request: Optional[str] = None
    received_response: Optional[str] = None
    verification_status: str
    diff_details: Optional[Dict[str, Any]] = None
    created_at: str

    class Config:
        from_attributes = True


class VerifyTriggerResponse(BaseModel):
    """
    Acknowledgement response when a fuzzing verification job is triggered.
    """
    status: str = Field(
        ...,
        description="'accepted' if the job was queued successfully."
    )
    finding_id: int = Field(
        ...,
        description="The finding ID that verification was triggered for."
    )
    message: str = Field(
        ...,
        description="Human-readable confirmation message."
    )


