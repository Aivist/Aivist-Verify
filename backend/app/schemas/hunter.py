class AuthRefreshRequestSchema(BaseModel):
    """
    A transient (never-persisted) re-authentication request descriptor — the
    'Identity Provider Anchor'. Replayed by the custody state machine when the
    active session dies mid-scan.
    """
    method: str = Field(default="POST", description="HTTP method of the login/refresh request.")
    url: str = Field(..., description="Absolute URL of the identity/login endpoint.")
    headers: Dict[str, str] = Field(default_factory=dict, description="Request headers.")
    body: Optional[Any] = Field(default=None, description="Request body (JSON dict or raw string).")


class BatchVerifyRequest(BaseModel):
    """
    Input contract for parallel multi-endpoint fuzzing (Step 8 Objective B).
    All findings must resolve to a single approved host (v1 single-host lock).
    """
    finding_ids: List[int] = Field(..., min_length=1, description="Findings to fuzz concurrently.")
    scope: List[str] = Field(
        default_factory=list,
        description=(
            "Unified host-scope declaration: an allow-list of host patterns "
            "(e.g. ['example.com', '*.api.example.com', '10.0.0.5:8443']). Empty => UNLOCKED "
            "(lab/localhost, byte-identical to today). When set it supersedes approved_host and "
            "is the single authorized boundary all traffic is fail-closed to."
        ),
    )
    model: Optional[str] = Field(
        default=None,
        description=(
            "Optional per-run LLM model override for the shadow deep verifier "
            "(unset => the configured provider default)."
        ),
    )
    approved_host: Optional[str] = Field(
        default=None,
        description=(
            "LEGACY single approved host (netloc). Kept as a backward-compatible alias: when "
            "`scope` is empty this maps to scope=[approved_host]. Derived from findings if omitted."
        ),
    )
    auth_refresh_request: Optional[AuthRefreshRequestSchema] = Field(
        default=None,
        description="Transient re-auth request for the shared custody controller. Not persisted.",
    )
    max_concurrency: int = Field(
        default=5, ge=1, le=20,
        description="Global cap on concurrent outbound fuzz requests across the batch.",
    )


class BatchVerifyResponse(BaseModel):
    """Acknowledgement for a queued parallel verification batch."""
    status: str = Field(..., description="'accepted' if the batch was queued successfully.")
    finding_ids: List[int] = Field(..., description="The findings queued for verification.")
    approved_host: str = Field(..., description="The single host the batch is locked to.")
    message: str = Field(..., description="Human-readable confirmation message.")


class AuthDryRunRequest(BaseModel):
    """Request to test an Identity Provider Anchor before launching a batch."""
    auth_refresh_request: AuthRefreshRequestSchema
    approved_host: Optional[str] = Field(
        default=None,
        description="Optional scope lock; if set, the dry-run refuses out-of-scope hosts.",
    )


class AuthDryRunResponse(BaseModel):
    """Result of a re-auth dry-run probe."""
    success: bool = Field(..., description="True if a fresh credential was extracted.")
    status_code: Optional[int] = Field(default=None, description="HTTP status of the probe.")
    extracted_kind: Optional[str] = Field(default=None, description="'cookie' or 'token' if extracted.")
    extracted_preview: Optional[str] = Field(default=None, description="Truncated preview of the credential.")
    message: str = Field(..., description="Human-readable diagnostic.")


