class HarIngestRequest(BaseModel):
    """
    Input contract for the HAR traffic ingestion endpoint.
    Accepts a standard HAR 1.2 JSON payload as produced by browser DevTools,
    Fiddler, Charles, mitmproxy, or Burp Suite exports.
    """
    log: Dict[str, Any] = Field(
        ...,
        description=(
            "The root 'log' object of a HAR 1.2 JSON file. "
            "Must contain an 'entries' array of HTTP request/response records."
        ),
    )

    threshold: float = Field(
        default=0.65,
        ge=0.0,
        le=1.0,
        description=(
            "Minimum exposure score threshold for traffic filtering. "
            "Entries below this score are pruned as noise. Default: 0.65."
        ),
    )


class HarIngestEntry(BaseModel):
    """
    A single high-value entry surfaced from HAR traffic pruning.
    """
    method: str = Field(..., description="HTTP method (GET, POST, etc.)")
    path: str = Field(..., description="Request URL path.")
    query_params: Dict[str, Any] = Field(default_factory=dict, description="Parsed query string parameters.")
    headers: Dict[str, str] = Field(default_factory=dict, description="Security-relevant request headers.")
    body: Optional[Any] = Field(default=None, description="Parsed request body (JSON dict or raw text).")
    exposure_score: float = Field(..., description="Computed heuristic exposure score [0.0, 1.0].")
    raw_http_string: str = Field(default="", description="Pre-reconstructed raw HTTP request text for direct textarea injection.")
    source_url: str = Field(default="", description="Original full URL from HAR entry.")
    is_login_candidate: bool = Field(
        default=False,
        description=(
            "Step 8: deterministically flagged as a likely identity/login endpoint "
            "(POST + login/auth/token/session/password markers). Used to pre-fill the "
            "Identity Provider Anchor panel for dynamic re-auth."
        ),
    )


class HarIngestResponse(BaseModel):
    """
    Output contract for the HAR ingestion endpoint.
    Returns filtered high-value endpoints after noise elimination.
    """
    status: str = Field(..., description="'success' or 'error'.")
    total_entries: int = Field(..., description="Total number of HAR entries received.")
    filtered_count: int = Field(..., description="Number of high-value entries after pruning.")
    threshold_used: float = Field(..., description="The exposure score threshold applied.")
    high_value_entries: List[HarIngestEntry] = Field(
        default_factory=list,
        description="Array of high-score entry points sorted by exposure score descending."
    )
    error_message: Optional[str] = Field(default=None, description="Error description if status is 'error'.")


# ==============================================================================
# Step D: Hunter Analysis Persistence Schemas
#
# Bridges the previously-broken Hunter -> Verify link: an analyzed request plus
# its AI-generated automation_payloads is persisted as a fuzzable
# VulnerabilityFinding (source="hunter"), returning a finding_id the verify
# endpoints can act on.
# ==============================================================================

class HunterPersistRequest(BaseModel):
    """
    Input contract for persisting an AI Logic Hunter analysis as a fuzzable
    finding. Structured data is stored in dedicated typed columns — NOT smuggled
    inside the ai_patch / poc_request text columns.
    """
    parsed_data: Dict[str, Any] = Field(
        ...,
        description=(
            "The structured HTTP request (method, path, query_params, headers, "
            "body) produced by /hunter/analyze. Stored in the parsed_request column."
        ),
    )
    automation_payloads: List[AutomationPayload] = Field(
        ...,
        min_length=1,
        description="The AI-generated attack payloads to fuzz. Stored in the automation_payloads column.",
    )
    target_url: Optional[str] = Field(
        default=None,
        description=(
            "Absolute base/target URL (scheme://host). Used to derive matched_at "
            "for the fuzzing base URL. If omitted, the backend derives it from the "
            "Host header inside parsed_data."
        ),
    )
    auth_refresh_request: Optional[AuthRefreshRequestSchema] = Field(
        default=None,
        description="Optional Identity Provider Anchor stored for single-target re-auth.",
    )
    report_markdown: Optional[str] = Field(
        default=None,
        description="Optional Gemini report markdown to retain in the ai_patch column for display.",
    )


class HunterPersistResponse(BaseModel):
    """Acknowledgement returned after persisting a Hunter analysis."""
    status: str = Field(..., description="'success' or 'error'.")
    finding_id: Optional[int] = Field(
        default=None,
        description="The integer id of the created VulnerabilityFinding (use with /verify/{finding_id}).",
    )
    message: str = Field(..., description="Human-readable confirmation or error diagnostic.")

